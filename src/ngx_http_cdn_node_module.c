// 创建配置
static void *ngx_http_cdn_node_create_main_conf(ngx_conf_t *cf) {
    ngx_http_cdn_node_conf_t *conf;

    conf = ngx_pcalloc(cf->pool, sizeof(ngx_http_cdn_node_conf_t));
    if (conf == NULL) {
        return NULL;
    }

    conf->headers = ngx_array_create(cf->pool, 4, sizeof(ngx_http_cdn_node_header_entry_conf_t));
    if (conf->headers == NULL) {
        return NULL;
    }

    return conf;
}

// 配置解析完成后, 为未设置的值填默认值
static char *ngx_http_cdn_node_init_main_conf(ngx_conf_t *cf, void *conf) {
    ngx_http_cdn_node_conf_t *config = conf;

    if (config->colo.data == NULL) {
        ngx_str_set(&config->colo, "");
    }

    if (config->sliver.data == NULL) {
        ngx_str_set(&config->sliver, "");
    }

    return NGX_CONF_OK;
}

// 由ngx_http_header_filter根据headers_out中的专用字段生成的header.
// 追加到headers列表只会产生重复项(Content-Length/Transfer-Encoding重复还会导致响应解析歧义), 所以禁止配置
static ngx_str_t cdn_node_reserved_headers[] = {
    ngx_string("Server"),
    ngx_string("Date"),
    ngx_string("Content-Type"),
    ngx_string("Content-Length"),
    ngx_string("Transfer-Encoding"),
    ngx_string("Connection"),
    ngx_string("Keep-Alive"),
    ngx_string("Last-Modified"),
    ngx_null_string
};

// 判断是否为RFC 9110中的tchar
static ngx_uint_t ngx_http_cdn_node_is_tchar(u_char c) {
    if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9')) {
        return 1;
    }

    return ngx_strchr("!#$%&'*+-.^_`|~", c) != NULL;
}

// header指令处理
static char *ngx_http_cdn_node_header_config(ngx_conf_t *cf, ngx_command_t *cmd, void *conf) {
    ngx_http_cdn_node_conf_t *config = conf;
    ngx_str_t *args = cf->args->elts;
    ngx_http_cdn_node_header_entry_conf_t *header;
    ngx_http_compile_complex_value_t ccv;
    ngx_str_t *reserved;
    size_t i;

    if (args[1].len == 0) {
        ngx_conf_log_error(NGX_LOG_EMERG, cf, 0, "empty header name in \"%V\"", &cmd->name);
        return NGX_CONF_ERROR;
    }

    for (i = 0; i < args[1].len; i++) {
        if (!ngx_http_cdn_node_is_tchar(args[1].data[i])) {
            ngx_conf_log_error(NGX_LOG_EMERG, cf, 0,
                               "invalid header name \"%V\" in \"%V\"", &args[1], &cmd->name);
            return NGX_CONF_ERROR;
        }
    }

    for (reserved = cdn_node_reserved_headers; reserved->len; reserved++) {
        if (reserved->len == args[1].len
            && ngx_strncasecmp(reserved->data, args[1].data, args[1].len) == 0)
        {
            ngx_conf_log_error(NGX_LOG_EMERG, cf, 0,
                               "header \"%V\" is generated by nginx and cannot be set by \"%V\"",
                               &args[1], &cmd->name);
            return NGX_CONF_ERROR;
        }
    }

    header = ngx_array_push(config->headers);
    if (header == NULL) {
        return NGX_CONF_ERROR;
    }

    header->header_name = args[1];

    ngx_memzero(&ccv, sizeof(ngx_http_compile_complex_value_t));
    ccv.cf = cf;
    ccv.value = &args[2];
    ccv.complex_value = &header->header_value;

    if (ngx_http_compile_complex_value(&ccv) != NGX_OK) {
        return NGX_CONF_ERROR;
    }

    return NGX_CONF_OK;
}

// trace响应中除字段值以外的固定文本, 用于计算缓冲区大小
#define CDN_NODE_TRACE_FIXED_TEXT \
    "h=\nip=\nts=.\nvisit_scheme=\nuag=\ncolo=\nsliver=\nhttp=\ntls=\n"

static ngx_str_t cdn_node_cache_control = ngx_string("Cache-Control");
static ngx_str_t cdn_node_no_store = ngx_string("no-store");
static ngx_str_t cdn_node_content_type_options = ngx_string("X-Content-Type-Options");
static ngx_str_t cdn_node_nosniff = ngx_string("nosniff");

// 向响应追加一个header
static ngx_int_t ngx_http_cdn_node_add_header(ngx_http_request_t *r,
    ngx_str_t *key, ngx_str_t *value)
{
    ngx_table_elt_t *h;

    h = ngx_list_push(&r->headers_out.headers);
    if (h == NULL) {
        return NGX_ERROR;
    }

    h->hash = 1;
    h->key = *key;
    h->value = *value;
    h->next = NULL;

    return NGX_OK;
}

// 生成/cdn-cgi/trace响应内容
static ngx_int_t ngx_http_cdn_node_trace_handler(ngx_http_request_t *r) {
    ngx_http_cdn_node_conf_t *config;
    ngx_buf_t *b;
    ngx_chain_t out;
    struct timespec ts;
    size_t size, len, tls_len;
    const char *tls;
    ngx_int_t rc;
    ngx_str_t scheme;
    ngx_str_t ua;

    if (!(r->method & (NGX_HTTP_GET|NGX_HTTP_HEAD))) {
        return NGX_HTTP_NOT_ALLOWED;
    }

    rc = ngx_http_discard_request_body(r);
    if (rc != NGX_OK) {
        return rc;
    }

    config = ngx_http_get_module_main_conf(r, ngx_http_cdn_node_module);

    clock_gettime(CLOCK_REALTIME, &ts);

    ngx_str_set(&scheme, "http");
#if (NGX_HTTP_SSL)
    if (r->connection->ssl) {
        ngx_str_set(&scheme, "https");
    }
#endif

    // 客户端可能不发送User-Agent
    if (r->headers_in.user_agent) {
        ua = r->headers_in.user_agent->value;
    } else {
        ngx_str_set(&ua, "");
    }

    tls = "off";
#if (NGX_HTTP_SSL)
    if (r->connection->ssl) {
        tls = SSL_get_version(r->connection->ssl->connection);
    }
#endif
    tls_len = ngx_strlen(tls);

    // 按实际字段长度从请求pool分配, 不再使用固定缓冲区, 超长Host/UA也能完整输出.
    // 各字段长度都有上限(请求头受large_client_header_buffers限制), 所以总大小有界.
    // 秒数占NGX_TIME_T_LEN, 小数部分固定2位
    size = sizeof(CDN_NODE_TRACE_FIXED_TEXT) - 1
           + r->headers_in.server.len
           + r->connection->addr_text.len
           + NGX_TIME_T_LEN + 2
           + scheme.len
           + ua.len
           + config->colo.len
           + config->sliver.len
           + r->http_protocol.len
           + tls_len;

    b = ngx_create_temp_buf(r->pool, size);
    if (b == NULL) {
        return NGX_HTTP_INTERNAL_SERVER_ERROR;
    }

    // ngx_slprintf以b->end为边界, 即使长度估算有误也只会截断而不会越界
    b->last = ngx_slprintf(b->last, b->end,
                           "h=%V\n"
                           "ip=%V\n"
                           "ts=%T.%02l\n"
                           "visit_scheme=%V\n"
                           "uag=%V\n"
                           "colo=%V\n"
                           "sliver=%V\n"
                           "http=%V\n"
                           "tls=%s\n",
                           &r->headers_in.server,
                           &r->connection->addr_text,
                           (time_t) ts.tv_sec, (long) (ts.tv_nsec / 10000000),
                           &scheme,
                           &ua,
                           &config->colo,
                           &config->sliver,
                           &r->http_protocol,
                           tls);

    len = b->last - b->pos;
    b->last_buf = 1;
    b->last_in_chain = 1;

    out.buf = b;
    out.next = NULL;

    r->headers_out.status = NGX_HTTP_OK;
    r->headers_out.content_length_n = len;
    r->headers_out.content_type.len = sizeof("text/plain") - 1;
    r->headers_out.content_type.data = (u_char *) "text/plain";

    // trace回显客户端IP/UA/Host:
    // no-store防止中间缓存把某个客户端的结果返回给其他人,
    // nosniff防止浏览器把回显内容当作HTML解析(反射型XSS)
    if (ngx_http_cdn_node_add_header(r, &cdn_node_cache_control,
                                     &cdn_node_no_store) != NGX_OK
        || ngx_http_cdn_node_add_header(r, &cdn_node_content_type_options,
                                        &cdn_node_nosniff) != NGX_OK)
    {
        return NGX_HTTP_INTERNAL_SERVER_ERROR;
    }

    // 本模块的响应即最终结果: 自行finalize并返回NGX_DONE,
    // 阻止phase引擎继续进入CONTENT阶段(proxy_pass/static等)
    rc = ngx_http_send_header(r);
    if (rc == NGX_ERROR || rc > NGX_OK || r->header_only) {
        ngx_http_finalize_request(r, rc);
        return NGX_DONE;
    }

    ngx_http_finalize_request(r, ngx_http_output_filter(r, &out));
    return NGX_DONE;
}

// 响应头过滤器: 在发送响应头时追加配置的header
// 所有响应(包括return/错误页/内部跳转后的响应)都会经过这里, 且此时可取到$status/$upstream_*等响应阶段变量
static ngx_int_t ngx_http_cdn_node_header_filter(ngx_http_request_t *r) {
    ngx_http_cdn_node_conf_t *config;
    ngx_http_cdn_node_header_entry_conf_t *header;
    ngx_uint_t i;
    ngx_str_t value;
    ngx_table_elt_t *h;

    // 子请求的响应头不会发给客户端, 跳过
    if (r != r->main) {
        return ngx_http_next_header_filter(r);
    }

    config = ngx_http_get_module_main_conf(r, ngx_http_cdn_node_module);
    if (config == NULL || config->headers->nelts == 0) {
        return ngx_http_next_header_filter(r);
    }

    header = config->headers->elts;
    for (i = 0; i < config->headers->nelts; i++) {
        // header filter中返回错误会直接断开连接, 求值失败时只记日志并跳过该header
        if (ngx_http_complex_value(r, &header[i].header_value, &value) != NGX_OK) {
            ngx_log_error(NGX_LOG_ERR, r->connection->log, 0,
                          "cdn_node: failed to evaluate header \"%V\"",
                          &header[i].header_name);
            continue;
        }

        // 与add_header一致: 值为空时不输出, 便于配合map按条件添加header
        if (value.len == 0) {
            continue;
        }

        h = ngx_list_push(&r->headers_out.headers);
        if (h == NULL) {
            return NGX_ERROR;
        }

        h->hash = 1;
        h->key = header[i].header_name;
        h->value = value;
        h->next = NULL;
    }

    return ngx_http_next_header_filter(r);
}

// /cdn-cgi/trace handler, 挂在PRECONTENT阶段, 在access阶段之后执行
static ngx_int_t ngx_http_cdn_node_trace_phase_handler(ngx_http_request_t *r) {
    ngx_http_cdn_node_conf_t *config;

    if (r->main->internal) {
        return NGX_DECLINED;
    }

    config = ngx_http_get_module_main_conf(r, ngx_http_cdn_node_module);
    if (config->headers->nelts == 0) {
        return NGX_DECLINED;
    }

    // 检查是否是/cdn-cgi/trace请求
    if (r->uri.len == sizeof("/cdn-cgi/trace") - 1 &&
        ngx_strncmp(r->uri.data, "/cdn-cgi/trace", sizeof("/cdn-cgi/trace") - 1) == 0) {
        return ngx_http_cdn_node_trace_handler(r);
    }

    return NGX_DECLINED;
}

// 模块初始化
static ngx_int_t ngx_http_cdn_node_init(ngx_conf_t *cf) {
    ngx_http_handler_pt *h;
    ngx_http_core_main_conf_t *cmcf;

    cmcf = ngx_http_conf_get_module_main_conf(cf, ngx_http_core_module);

    h = ngx_array_push(&cmcf->phases[NGX_HTTP_PRECONTENT_PHASE].handlers);
    if (h == NULL) {
        return NGX_ERROR;
    }

    *h = ngx_http_cdn_node_trace_phase_handler;

    ngx_http_next_header_filter = ngx_http_top_header_filter;
    ngx_http_top_header_filter = ngx_http_cdn_node_header_filter;

    return NGX_OK;
}
